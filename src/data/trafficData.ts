export const getSignById = (id: string): TrafficSign => {
  const sign = TRAFFIC_SIGNS.find((s) => s.id === id);
  if (!sign) {
    throw new Error(`Rambu dengan ID "${id}" tidak ditemukan.`);
  }
  return sign;
};

